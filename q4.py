def addition(a, b):
    return a + b


def subtraction(a, b):
    return a - b


def multiplication(a, b):
    return a * b


def division(a, b):
    return a / b


print("Addition =", addition(20, 10))
print("Subtraction =", subtraction(20, 10))
print("Multiplication =", multiplication(20, 10))
print("Division =", division(20, 10))