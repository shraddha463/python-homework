class Calculator:

    def add(self, a, b):
        print("Addition:", a + b)

    def subtract(self, a, b):
        print("Subtraction:", a - b)

    def multiply(self, a, b):
        print("Multiplication:", a * b)

    def divide(self, a, b):
        print("Division:", a / b)


cal = Calculator()

cal.add(10, 5)
cal.subtract(10, 5)
cal.multiply(10, 5)
cal.divide(10, 5)